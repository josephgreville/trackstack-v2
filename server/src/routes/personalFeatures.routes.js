import { Router } from 'express';
import { requireAuth } from '../middleware/auth.js';
import { validate } from '../middleware/validate.js';
import { asyncHandler } from '../utils/asyncHandler.js';
import { albumIdSchema, historyCreateSchema, historyIdParamsSchema, historyReviewSchema, queueBuildSchema, queueCreateSchema, queueIdSchema, wantlistAcquireSchema, wantlistCreateSchema, wantlistUpdateSchema } from '../validators/schemas.js';
import { historyCreate, historyIndex, historyInsights, historyUpdate, queueBuild, queueCreate, queueDelete, queueIndex, queueListen, wantlistAcquire, wantlistCreate, wantlistDelete, wantlistIndex, wantlistUpdate } from '../controllers/personalFeaturesController.js';

const router = Router();
router.use(requireAuth);
router.get('/wantlist', asyncHandler(wantlistIndex));
router.post('/wantlist', validate({ body: wantlistCreateSchema }), asyncHandler(wantlistCreate));
router.delete('/wantlist/:id', validate({ params: albumIdSchema }), asyncHandler(wantlistDelete));
router.patch('/wantlist/:id', validate({ params: albumIdSchema, body: wantlistUpdateSchema }), asyncHandler(wantlistUpdate));
router.post('/wantlist/:id/acquire', validate({ params: albumIdSchema, body: wantlistAcquireSchema }), asyncHandler(wantlistAcquire));
router.get('/queue', asyncHandler(queueIndex));
router.post('/queue/build', validate({ body: queueBuildSchema }), asyncHandler(queueBuild));
router.post('/queue', validate({ body: queueCreateSchema }), asyncHandler(queueCreate));
router.delete('/queue/:id', validate({ params: queueIdSchema }), asyncHandler(queueDelete));
router.post('/queue/:id/listen', validate({ params: queueIdSchema }), asyncHandler(queueListen));
router.get('/history', asyncHandler(historyIndex));
router.get('/history/insights', asyncHandler(historyInsights));
router.post('/history', validate({ body: historyCreateSchema }), asyncHandler(historyCreate));
router.patch('/history/:historyId', validate({ params: historyIdParamsSchema, body: historyReviewSchema }), asyncHandler(historyUpdate));
export default router;
